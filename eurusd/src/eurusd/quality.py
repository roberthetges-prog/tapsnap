"""Generate data/DATA_QUALITY.md for the processed EUR/USD dataset.

Run:  python -m eurusd.quality
Everything reported here is computed from the parquet/csv files in data/processed;
nothing is hard-coded.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from eurusd.data import PROC_DIR, PROJECT_DIR, load_ecb, load_ohlc, load_yahoo

DATA_DIR = PROJECT_DIR / "data"
RAW_DIR = DATA_DIR / "raw" / "histdata"
PIP = 1e-4


def md_table(df: pd.DataFrame, floatfmt: str = "{:.5f}") -> str:
    df = df.copy()
    for c in df.columns:
        if pd.api.types.is_float_dtype(df[c]):
            df[c] = df[c].map(lambda v: "" if pd.isna(v) else floatfmt.format(v))
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join(["---"] * len(cols)) + "|"]
    for _, row in df.iterrows():
        lines.append("| " + " | ".join(str(v) for v in row.values) + " |")
    return "\n".join(lines)


def fmt_ts(t) -> str:
    return pd.Timestamp(t).strftime("%Y-%m-%d %H:%M")


def is_weekend_gap(start: pd.Timestamp, end: pd.Timestamp) -> bool:
    """True if the closed interval [start, end] contains any part of Saturday UTC."""
    # any Saturday 00:00 UTC strictly inside, or start/end is on Saturday
    if start.weekday() == 5 or end.weekday() == 5:
        return True
    days = pd.date_range(start.normalize(), end.normalize(), freq="D")
    return bool((days.weekday == 5).any())


def main() -> None:
    m1 = load_ohlc("M1")
    d1 = load_ohlc("D1")
    stats = json.loads((PROC_DIR / "build_stats.json").read_text())
    dl_log = json.loads((RAW_DIR / "download_log.json").read_text()) if (RAW_DIR / "download_log.json").exists() else []
    out: list[str] = []
    P = out.append

    P("# EUR/USD data quality report\n")
    P(f"Generated by `python -m eurusd.quality` on {pd.Timestamp.now(tz='UTC'):%Y-%m-%d %H:%M} UTC.\n")
    P("Source: HistData.com ASCII 1-minute bid bars, EST (UTC-5, no DST) shifted +5h to UTC. "
      "Cross-checks: Yahoo Finance (EURUSD=X), ECB daily reference rate.\n")

    # ------------------------------------------------------------------ downloads
    P("## 1. Downloads (HistData)\n")
    if dl_log:
        dl = pd.DataFrame(dl_log)
        dl["size_MB"] = dl["size"] / 1e6
        P(md_table(dl[["period", "file", "size_MB", "status"]], "{:.2f}"))
        P("")
    P(f"Total raw zips: {len(list(RAW_DIR.glob('*.zip')))}, "
      f"{sum(p.stat().st_size for p in RAW_DIR.glob('*.zip'))/1e6:.1f} MB.\n")

    # ------------------------------------------------------------------ M1 summary
    P("## 2. M1 summary\n")
    P(f"* Raw rows parsed: **{stats['rows_raw']:,}**; duplicate timestamps removed: **{stats['duplicates_removed']:,}** "
      f"(kept last occurrence); final rows: **{len(m1):,}**.")
    P(f"* Range: **{m1.index.min()}** to **{m1.index.max()}** (UTC).")
    P(f"* Index is unique: {m1.index.is_unique}; monotonic increasing: {m1.index.is_monotonic_increasing}.")
    P(f"* Any NaN: {int(m1.isna().sum().sum())}. Volume > 0 rows: {int((m1['volume'] > 0).sum()):,} "
      f"({(m1['volume'] > 0).mean()*100:.2f}%) - HistData 'volume' is essentially always 0; ignore it.")
    P(f"* Price precision: min tick distance between distinct closes = "
      f"{np.diff(np.unique(m1['close'].values)).min():.6f}.\n")

    # per-file
    pf = pd.DataFrame(stats["per_file"]).T.reset_index().rename(columns={"index": "file"})
    P("### Per source file\n")
    P(md_table(pf))
    P("")

    # ------------------------------------------------------------------ coverage per year
    P("## 3. Coverage per year (M1)\n")
    yr = m1.groupby(m1.index.year)
    cov = pd.DataFrame({
        "bars": yr.size(),
        "first": yr.apply(lambda g: fmt_ts(g.index.min())),
        "last": yr.apply(lambda g: fmt_ts(g.index.max())),
        "trading_days(UTC)": yr.apply(lambda g: g.index.normalize().nunique()),
    })
    # expected minutes: ~ (weeks * 5 days * 24h * 60) ~ 5*1440 per week
    cov["bars_per_trading_day"] = (cov["bars"] / cov["trading_days(UTC)"]).round(0)
    cov.index.name = "year"
    P(md_table(cov.reset_index(), "{:.0f}"))
    P("")
    P("Note: a full 24h weekday has 1440 M1 bars; HistData only emits a bar when at least one tick arrived, "
      "so quiet hours (esp. pre-2010, and the 22:00-23:00 UTC daily rollover) produce fewer bars. "
      "Low bars/day in early years reflects thin tick feeds, not necessarily missing data.\n")

    # ------------------------------------------------------------------ gaps
    P("## 4. Gaps > 1 hour between consecutive M1 bars\n")
    idx = m1.index
    diffs = pd.Series(idx[1:] - idx[:-1], index=idx[1:])
    gaps = diffs[diffs > pd.Timedelta(hours=1)]
    g = pd.DataFrame({"gap_end": gaps.index, "gap": gaps.values})
    g["gap_start"] = g["gap_end"] - g["gap"]
    g["weekend"] = [is_weekend_gap(s, e) for s, e in zip(g["gap_start"], g["gap_end"])]
    g["hours"] = g["gap"].dt.total_seconds() / 3600
    nonwk = g[~g["weekend"]].sort_values("hours", ascending=False)
    wk = g[g["weekend"]].copy()
    P(f"Total gaps > 1h: {len(g):,}; of which spanning a Saturday (weekend closures): {len(wk):,}; "
      f"**non-weekend gaps: {len(nonwk):,}**.\n")
    P(f"Non-weekend gaps by year: " + ", ".join(
        f"{y}: {n}" for y, n in nonwk.groupby(nonwk["gap_start"].dt.year).size().items()) + "\n")
    P("### 30 largest non-weekend gaps\n")
    t = nonwk.head(30)[["gap_start", "gap_end", "hours"]].copy()
    t["gap_start"] = t["gap_start"].map(fmt_ts); t["gap_end"] = t["gap_end"].map(fmt_ts)
    t["weekday_start"] = nonwk.head(30)["gap_start"].dt.day_name().values
    P(md_table(t, "{:.1f}"))
    P("")
    # weekend anomalies: normal weekend = Fri ~22:00 UTC -> Sun ~22:00 UTC (48h). Flag long ones.
    wk["excess_h"] = wk["hours"] - 48
    long_wk = wk[wk["hours"] > 52].sort_values("hours", ascending=False)
    P(f"### Weekend gaps longer than 52h (normal weekend is ~48h, Fri 22:00 -> Sun 22:00 UTC): {len(long_wk)}\n")
    t = long_wk.head(30)[["gap_start", "gap_end", "hours"]].copy()
    t["gap_start"] = t["gap_start"].map(fmt_ts); t["gap_end"] = t["gap_end"].map(fmt_ts)
    P(md_table(t, "{:.1f}"))
    P("")
    # typical weekend open/close times by year
    wk_norm = wk[(wk["hours"] >= 40) & (wk["hours"] <= 60)]
    wo = wk_norm.groupby(wk_norm["gap_start"].dt.year).agg(
        fri_close_med=("gap_start", lambda s: pd.Series(s.dt.hour + s.dt.minute / 60).median()),
        sun_open_med=("gap_end", lambda s: pd.Series(s.dt.hour + s.dt.minute / 60).median()),
        n=("hours", "size"))
    wo.index.name = "year"
    P("### Typical weekend close/open hour (UTC, median per year)\n")
    P(md_table(wo.reset_index(), "{:.2f}"))
    P("\nIf the timezone shift is right, Friday close should be ~22:00 UTC and Sunday open ~22:00 UTC "
      "all year (EST without DST). Values near 21:00/22:00 and 22:00/23:00 are consistent with that.\n")

    # ------------------------------------------------------------------ bad bars
    P("## 5. Bar sanity checks (M1)\n")
    hl = m1[m1["high"] < m1["low"]]
    zero = m1[m1["high"] == m1["low"]]
    oc_out = m1[(m1["open"] > m1["high"]) | (m1["open"] < m1["low"]) | (m1["close"] > m1["high"]) | (m1["close"] < m1["low"])]
    nonpos = m1[(m1[["open", "high", "low", "close"]] <= 0).any(axis=1)]
    P(f"* high < low: **{len(hl):,}**")
    P(f"* zero range (high == low): **{len(zero):,}** ({len(zero)/len(m1)*100:.2f}% of bars). "
      f"Zero-range bars by year: " + ", ".join(f"{y}: {n}" for y, n in zero.groupby(zero.index.year).size().items()))
    P(f"* open/close outside [low, high]: **{len(oc_out):,}**")
    P(f"* non-positive prices: **{len(nonpos):,}**")
    # price level plausibility
    P(f"* price range: min low = {m1['low'].min():.5f} ({fmt_ts(m1['low'].idxmin())}), "
      f"max high = {m1['high'].max():.5f} ({fmt_ts(m1['high'].idxmax())}). "
      f"EUR/USD has traded ~0.82-1.60 since 2000; anything outside is suspicious.")
    rng_pips = (m1["high"] - m1["low"]) / PIP
    P(f"* M1 range (pips): median {rng_pips.median():.1f}, p99 {rng_pips.quantile(0.99):.1f}, "
      f"p99.99 {rng_pips.quantile(0.9999):.1f}, max {rng_pips.max():.1f} at {fmt_ts(rng_pips.idxmax())}.\n")
    big_rng = rng_pips[rng_pips > 100].sort_values(ascending=False)
    P(f"### M1 bars with intra-bar range > 100 pips: {len(big_rng)}\n")
    t = m1.loc[big_rng.index[:30]].copy()
    t["range_pips"] = big_rng.head(30).values
    t = t.reset_index(); t["time"] = t["time"].map(fmt_ts)
    P(md_table(t[["time", "open", "high", "low", "close", "range_pips"]], "{:.5f}"))
    P("")

    # ------------------------------------------------------------------ extreme returns
    P("## 6. Extreme 1-minute close-to-close returns (|r| > 0.5%)\n")
    r = m1["close"].pct_change()
    gap_before = diffs.reindex(m1.index)
    ext = m1[r.abs() > 0.005].copy()
    ext["ret_pct"] = r[ext.index] * 100
    ext["prev_close"] = m1["close"].shift(1)[ext.index]
    ext["gap_before_min"] = (gap_before[ext.index].dt.total_seconds() / 60)
    # reversion check: close 5 bars later relative to prev_close
    pos = m1.index.get_indexer(ext.index)
    c = m1["close"].values
    later = np.array([c[min(p + 5, len(c) - 1)] for p in pos])
    ext["ret_after_5bars_vs_prev_pct"] = (later / ext["prev_close"].values - 1) * 100
    ext["reverted"] = (np.sign(ext["ret_after_5bars_vs_prev_pct"]) != np.sign(ext["ret_pct"])) | \
                      (ext["ret_after_5bars_vs_prev_pct"].abs() < ext["ret_pct"].abs() * 0.25)
    P(f"Count: **{len(ext)}**. 'gap_before_min' > 1 means the move spans a data gap (weekend/holiday open), "
      "'reverted' = True means 5 bars later the price is back near the pre-move level (suspicious of a bad tick, "
      "or a flash move). Judge each against known events (SNB 2015-01-15, Brexit 2016-06-24, US election 2016-11-09, "
      "Lehman 2008, Covid March 2020, 2022 flash moves).\n")
    t = ext.reset_index(); t["time"] = t["time"].map(fmt_ts)
    P(md_table(t[["time", "prev_close", "open", "high", "low", "close", "ret_pct", "gap_before_min",
                  "ret_after_5bars_vs_prev_pct", "reverted"]].sort_values("time"), "{:.4f}"))
    P("")
    # also |r|>0.3% count by year for context
    P("Count of |1-min return| > 0.3% by year: " + ", ".join(
        f"{y}: {n}" for y, n in r[r.abs() > 0.003].groupby(r[r.abs() > 0.003].index.year).size().items()) + "\n")

    # ------------------------------------------------------------------ weekend bars
    P("## 7. Weekend bars\n")
    wd = m1.index.weekday
    hr = m1.index.hour
    sat = m1[wd == 5]
    sun_early = m1[(wd == 6) & (hr < 21)]
    fri_late = m1[(wd == 4) & (hr >= 22)]
    P(f"* Saturday bars: **{len(sat):,}**" + (
        "; by year: " + ", ".join(f"{y}: {n}" for y, n in sat.groupby(sat.index.year).size().items()) if len(sat) else ""))
    P(f"* Sunday bars before 21:00 UTC: **{len(sun_early):,}**" + (
        "; by year: " + ", ".join(f"{y}: {n}" for y, n in sun_early.groupby(sun_early.index.year).size().items()) if len(sun_early) else ""))
    P(f"* Friday bars at/after 22:00 UTC: **{len(fri_late):,}**" + (
        "; by year: " + ", ".join(f"{y}: {n}" for y, n in fri_late.groupby(fri_late.index.year).size().items()) if len(fri_late) else ""))
    if len(sat):
        t = sat.head(10).reset_index(); t["time"] = t["time"].map(fmt_ts)
        P("\nFirst Saturday bars:\n")
        P(md_table(t))
    P("\nThese are kept in the dataset as-is (not deleted); the D1 resample will contain Saturday/Sunday rows for them. "
      "Sunday bars from ~22:00 UTC are the normal weekly open.\n")

    # ------------------------------------------------------------------ daily range stats
    P("## 8. Daily range statistics by year (UTC days, D1 resample)\n")
    bars_per_day = m1.groupby(m1.index.normalize()).size()
    d = d1.copy()
    d["range_pips"] = (d["high"] - d["low"]) / PIP
    d["m1_bars"] = bars_per_day.reindex(d.index).values
    d["weekday"] = d.index.weekday
    full = d[(d["weekday"] < 5) & (d["m1_bars"] >= 600)]   # weekdays with reasonable coverage
    dr = full.groupby(full.index.year)["range_pips"].agg(["mean", "median", "std", "max", "count"])
    dr.columns = ["mean_pips", "median_pips", "std_pips", "max_pips", "days"]
    dr["max_day"] = full.groupby(full.index.year)["range_pips"].idxmax().map(lambda t: t.strftime("%Y-%m-%d"))
    dr["mean_close"] = full.groupby(full.index.year)["close"].mean()
    dr["ann_vol_pct(daily cc)"] = (np.log(d1["close"]).diff()[d1.index.weekday < 5]
                                   .groupby(d1.index[d1.index.weekday < 5].year).std() * np.sqrt(252) * 100)
    dr.index.name = "year"
    P("Weekdays with >= 600 M1 bars only (days: count used). Range = (high - low)/0.0001.\n")
    P(md_table(dr.reset_index(), "{:.1f}"))
    P("")
    P(f"D1 rows total: {len(d1):,}; weekday rows: {int((d1.index.weekday < 5).sum()):,}; "
      f"weekend rows (Sat/Sun): {int((d1.index.weekday >= 5).sum()):,} (Sunday rows are the 22:00-24:00 UTC open stub).\n")

    # ------------------------------------------------------------------ resampled sanity
    P("## 9. Resampled timeframes\n")
    rows = []
    for tf in ("M1", "M5", "M15", "M30", "H1", "H4", "D1"):
        df = load_ohlc(tf)
        p = PROC_DIR / f"EURUSD_{tf}.parquet"
        rows.append({"tf": tf, "bars": len(df), "first": fmt_ts(df.index.min()), "last": fmt_ts(df.index.max()),
                     "file_MB": p.stat().st_size / 1e6, "hi<lo": int((df['high'] < df['low']).sum()),
                     "unique_idx": df.index.is_unique})
    P(md_table(pd.DataFrame(rows), "{:.2f}"))
    h1 = load_ohlc("H1")
    chk = h1.loc["2024-03-05 13:00":"2024-03-05 13:00"]
    m1c = m1.loc["2024-03-05 13:00":"2024-03-05 13:59"]
    P(f"\nSpot check H1 2024-03-05 13:00 vs M1 13:00-13:59: open {chk['open'].iloc[0]:.5f}=={m1c['open'].iloc[0]:.5f}, "
      f"high {chk['high'].iloc[0]:.5f}=={m1c['high'].max():.5f}, low {chk['low'].iloc[0]:.5f}=={m1c['low'].min():.5f}, "
      f"close {chk['close'].iloc[0]:.5f}=={m1c['close'].iloc[-1]:.5f}, n_m1={len(m1c)}.\n")

    # ------------------------------------------------------------------ Yahoo cross-check
    P("## 10. Cross-check vs Yahoo Finance\n")
    try:
        yd = load_yahoo("EURUSD_D1")
        P(f"Yahoo EURUSD=X daily: {len(yd):,} rows, {yd.index.min()} .. {yd.index.max()}. "
          f"Timestamp hour distribution (UTC): {yd.index.hour.value_counts().to_dict()}.")
        # Yahoo daily stamps are ~00:00 or 23:00 UTC of the trading date; compare by calendar date
        yd_date = yd.copy()
        yd_date.index = (yd_date.index + pd.Timedelta(hours=1)).normalize().tz_localize(None)
        hd = d1.copy(); hd.index = hd.index.tz_localize(None)
        both = hd.join(yd_date, how="inner", lsuffix="_hd", rsuffix="_y")
        both = both[both.index.weekday < 5]
        diff = (both["close_hd"] - both["close_y"]).abs() / PIP
        rc = np.log(both["close_hd"]).diff().corr(np.log(both["close_y"]).diff())
        P(f"* Overlapping weekdays: **{len(both):,}** ({both.index.min().date()} .. {both.index.max().date()}).")
        P(f"* |close diff|: median **{diff.median():.1f} pips**, mean {diff.mean():.1f}, p90 {diff.quantile(0.9):.1f}, "
          f"p99 **{diff.quantile(0.99):.1f} pips**, max {diff.max():.1f} ({diff.idxmax().date()}).")
        P(f"* correlation of daily log returns: **{rc:.4f}**.")
        dpy = diff.groupby(diff.index.year).agg(["median", lambda s: s.quantile(0.99), "max", "size"])
        dpy.columns = ["median_pips", "p99_pips", "max_pips", "days"]
        dpy.index.name = "year"
        P("\nPer year:\n")
        P(md_table(dpy.reset_index(), "{:.1f}"))
        P("\nCaveat: Yahoo's EURUSD=X 'close' for a date is a snapshot taken near end of the UTC/London day (and "
          "historically has been flaky), while our D1 close is the last bid tick before 00:00 UTC; a few pips of "
          "systematic difference is expected and not an error. Large outliers are listed below.\n")
        big = diff[diff > 30].sort_values(ascending=False).head(15)
        if len(big):
            t = both.loc[big.index, ["close_hd", "close_y"]].copy(); t["diff_pips"] = big.values
            t = t.reset_index().rename(columns={"index": "date"}); t["date"] = t["date"].dt.strftime("%Y-%m-%d")
            P(md_table(t, "{:.5f}"))
            P("")
    except Exception as e:  # noqa: BLE001
        P(f"Yahoo daily cross-check unavailable: {e}\n")
    try:
        yh = load_yahoo("EURUSD_H1")
        P(f"Yahoo EURUSD=X hourly: {len(yh):,} rows, {yh.index.min()} .. {yh.index.max()}. "
          f"Minute-of-hour of timestamps: {sorted(set(yh.index.minute))}.")
        yh2 = yh.copy()
        yh2.index = yh2.index.floor("h")
        bothh = h1.join(yh2, how="inner", lsuffix="_hd", rsuffix="_y")
        diffh = (bothh["close_hd"] - bothh["close_y"]).abs() / PIP
        rch = np.log(bothh["close_hd"]).diff().corr(np.log(bothh["close_y"]).diff())
        P(f"* Overlapping hours: **{len(bothh):,}**; |close diff| median **{diffh.median():.1f} pips**, "
          f"p99 **{diffh.quantile(0.99):.1f} pips**, max {diffh.max():.1f} ({fmt_ts(diffh.idxmax())}); "
          f"hourly log-return correlation **{rch:.4f}**.")
        # also compare opens (Yahoo hourly 'close' may be mid-bar snapshot)
        diffo = (bothh["open_hd"] - bothh["open_y"]).abs() / PIP
        P(f"* |open diff|: median {diffo.median():.1f} pips, p99 {diffo.quantile(0.99):.1f} pips.\n")
    except Exception as e:  # noqa: BLE001
        P(f"Yahoo hourly cross-check unavailable: {e}\n")
    try:
        y6 = load_yahoo("6E_D1")
        P(f"Yahoo 6E=F (CME euro FX futures, front-month continuous) daily: {len(y6):,} rows, "
          f"{y6.index.min().date()} .. {y6.index.max().date()}. Saved for reference only "
          "(futures price = spot + carry; not directly comparable to spot closes).\n")
    except Exception as e:  # noqa: BLE001
        P(f"Yahoo 6E=F unavailable: {e}\n")

    # ------------------------------------------------------------------ ECB cross-check
    P("## 11. Cross-check vs ECB reference rate\n")
    try:
        ecb = load_ecb()
        P(f"ECB EXR/D.USD.EUR.SP00.A: {len(ecb):,} rows, {ecb.index.min().date()} .. {ecb.index.max().date()}.")
        # ECB fixing: 14:15 CET/CEST -> convert to UTC per date
        fix_local = pd.DatetimeIndex(ecb.index + pd.Timedelta(hours=14, minutes=15)).tz_localize("Europe/Frankfurt")
        fix_utc = fix_local.tz_convert("UTC")
        # nearest M1 close at or before fixing time (within 30 min)
        m1c = m1["close"]
        pos = m1c.index.searchsorted(fix_utc, side="right") - 1
        valid = pos >= 0
        got_ts = m1c.index[pos[valid]]
        within = (fix_utc[valid] - got_ts) <= pd.Timedelta(minutes=30)
        cmp = pd.DataFrame({"ecb": ecb.values[valid][within], "hd_1415CET": m1c.values[pos[valid]][within]},
                           index=ecb.index[valid][within])
        de = (cmp["hd_1415CET"] - cmp["ecb"]).abs() / PIP
        rce = np.log(cmp["hd_1415CET"]).diff().corr(np.log(cmp["ecb"]).diff())
        P(f"* Matched ECB fixings to the M1 bid close at/just before 14:15 Frankfurt time: **{len(cmp):,}** days "
          f"(ECB dates with no HistData bar within 30 min before the fixing: {int((~within).sum()) + int((~valid).sum())}).")
        P(f"* |diff| (HistData bid vs ECB mid-ish fixing): median **{de.median():.1f} pips**, p90 {de.quantile(0.9):.1f}, "
          f"p99 **{de.quantile(0.99):.1f} pips**, max {de.max():.1f} ({de.idxmax().date()}).")
        P(f"* correlation of daily log changes: **{rce:.4f}**.")
        dpe = de.groupby(de.index.year).agg(["median", lambda s: s.quantile(0.99), "max", "size"])
        dpe.columns = ["median_pips", "p99_pips", "max_pips", "days"]; dpe.index.name = "year"
        P("\nPer year:\n")
        P(md_table(dpe.reset_index(), "{:.1f}"))
        P("\nNote: the ECB rate is a mid reference from a concertation at ~14:10-14:15 CET, so a ~0.5-1.5 pip bid/mid "
          "offset plus a few pips of timing noise is expected; the median above being a small single-digit number "
          "confirms the EST->UTC shift (a wrong offset would show up as a much larger, DST-dependent error).\n")
        big = de[de > 30].sort_values(ascending=False).head(15)
        if len(big):
            t = cmp.loc[big.index].copy(); t["diff_pips"] = big.values
            t = t.reset_index().rename(columns={"index": "date"}); t["date"] = t["date"].dt.strftime("%Y-%m-%d")
            P("Largest ECB discrepancies (> 30 pips):\n")
            P(md_table(t, "{:.5f}"))
            P("")
    except Exception as e:  # noqa: BLE001
        P(f"ECB cross-check unavailable: {e}\n")

    # ------------------------------------------------------------------ files
    P("## 12. Processed files\n")
    rows = [{"file": p.name, "size_MB": p.stat().st_size / 1e6} for p in sorted(PROC_DIR.iterdir()) if p.is_file()]
    P(md_table(pd.DataFrame(rows), "{:.2f}"))
